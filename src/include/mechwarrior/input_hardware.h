#ifndef MECHWARRIOR_INPUT_HARDWARE_H
#define MECHWARRIOR_INPUT_HARDWARE_H

/* BIOS keyboard words contain the scan byte above the ASCII byte. */
enum { BIOS_KEY_SCAN_SHIFT=8,ASCII_CHARACTER_LIMIT=0x80,
    ASCII_CASE_DISTANCE='a'-'A',ASCII_CONTROL_MARKER=0x80 };

enum { KEYBOARD_BREAK_FLAG=0x80,KEYBOARD_SCAN_MASK=0x7F,
    KEYBOARD_ACKNOWLEDGE_BIT=0x80,KEYBOARD_INTERRUPT=0x09,BIOS_TICK_INTERRUPT=0x1C,
    BTECH_KEYBOARD_HANDLER_VECTOR=0x1BF52CCB,BTECH_BIOS_TICK_HANDLER_VECTOR=0x1BF52EAA };

enum { BIOS_KEYBOARD_SHIFT_FLAGS=0x17,
    BIOS_SHIFT_RIGHT_SHIFT=0x01,BIOS_SHIFT_LEFT_SHIFT=0x02,
    BIOS_SHIFT_EITHER_SHIFT=BIOS_SHIFT_RIGHT_SHIFT|BIOS_SHIFT_LEFT_SHIFT,
    BIOS_SHIFT_CONTROL=0x04,BIOS_SHIFT_ALT=0x08,BIOS_SHIFT_SCROLL_LOCK=0x10,
    BIOS_SHIFT_NUM_LOCK=0x20,BIOS_SHIFT_CAPS_LOCK=0x40,BIOS_SHIFT_INSERT=0x80,
    BIOS_SHIFT_CLEAR_NUM_LOCK=0xDF,
    BIOS_KEYBOARD_COMPATIBILITY_STATE=0x96,KEYBOARD_COMPATIBILITY_INTERCEPT_STATE=0x10 };

enum { BIOS_KEY_BUFFER_FIRST=0x1E,BIOS_KEY_BUFFER_END=0x3E,
    BIOS_KEY_BUFFER_WORD_BYTES=2,BIOS_KEY_BUFFER_LAST=BIOS_KEY_BUFFER_END-BIOS_KEY_BUFFER_WORD_BYTES,
    BIOS_KEY_BUFFER_BEFORE_FIRST=BIOS_KEY_BUFFER_FIRST-BIOS_KEY_BUFFER_WORD_BYTES,
    BIOS_KEY_BUFFER_WORDS=(BIOS_KEY_BUFFER_END-BIOS_KEY_BUFFER_FIRST)/BIOS_KEY_BUFFER_WORD_BYTES };

/* Native scan-translation attributes and high-bit character-table entries. */
enum { KEYBOARD_ATTRIBUTE_HELD=0x01,KEYBOARD_ATTRIBUTE_ALPHABETIC=0x04,
    KEYBOARD_ATTRIBUTE_DIRECTION_MASK=0xF8,KEYBOARD_ATTRIBUTE_GROUP_SHIFT=3,
    KEYBOARD_ATTRIBUTE_GROUP_MASK=0x01,KEYBOARD_ATTRIBUTE_DIRECTION_SHIFT=4,
    KEYBOARD_ATTRIBUTE_CLEAR_HELD=0xFE,
    KEYBOARD_CHARACTER_SPECIAL=0x80,KEYBOARD_CHARACTER_VALUE_MASK=0x7F,
    KEYBOARD_CHARACTER_TOGGLE_MASK=0x70,KEYBOARD_CHARACTER_CAPS_LOCK=0x40 };

enum { JOYSTICK_A=0,JOYSTICK_B=1,JOYSTICK_A_BUTTON_ONE=0,JOYSTICK_A_BUTTON_TWO=1,
    JOYSTICK_BUTTON_PAIR_MASK=0x02,JOYSTICK_BUTTON_INDEX_MASK=0x03,
    GAMEPORT_BUTTON_SHIFT=4,GAMEPORT_BUTTON_LEVEL_MASK=0x01,GAMEPORT_DISCONNECTED=0xFF,
    MOUSE_BUTTON_LEFT=0,MOUSE_BUTTON_RIGHT=1,MOUSE_BUTTON_COUNT=2 };

enum { JOYSTICK_AXIS_COUNT=4,JOYSTICK_AXES_PER_PAIR=2,JOYSTICK_AXIS_PAIR_POSITION_MASK=1,
    GAMEPORT_JOYSTICK_A_AXES_MASK=0x03,GAMEPORT_JOYSTICK_B_AXES_MASK=0x0C,
    JOYSTICK_AXIS_TIMING_LIMIT=0xFF,JOYSTICK_TIMING_HIGH_BYTE_MASK=0xFF00,
    JOYSTICK_CALIBRATION_PORT_SAMPLES=1000,JOYSTICK_LOOP_CALIBRATION_NUMERATOR=0x6FCC,
    JOYSTICK_AXIS_RECIPROCAL_NUMERATOR=0x7F00,JOYSTICK_PRESENCE_DELAY_LOOPS=20,
    PIT_CHANNEL_ZERO_LATCH=0x00,PIT_CHANNEL_ZERO_MODE3_LATCH=0x06 };

#endif
